"""Turn the rep-card callouts from the Notion CRM into rep_cards INSERTs.

Input: a JSON file, a list of {"notion_page_id": "...", "callout": "<callout ...>...</callout>"}
       (the callout block exactly as the Notion fetch returns it).
Output: SQL on stdout. Each insert finds its trigger event by notion_page_id and
        upserts on trigger_event_id, so re-running replaces the cards.

Usage: python -I rep_card_to_sql.py cards.json > rep_cards_YYYY-MM-DD.sql
"""
import json
import re
import sys
from datetime import date

MONTHS = {m: i for i, m in enumerate(
    ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"], 1)}


def plain(text: str) -> str:
    """Notion markdown -> readable plain text (links kept as 'text (url)')."""
    t = re.sub(r"<br\s*/?>", "\n", text)
    t = re.sub(r"</?(b|i|u|s|span)[^>]*>", "", t)
    t = re.sub(r"\[([^\]]+)\]\(mailto:[^)]+\)", r"\1", t)
    t = re.sub(r"\[([^\]]+)\]\((https?://[^)]+)\)",
               lambda m: m.group(1) if m.group(1) in m.group(2) else f"{m.group(1)} ({m.group(2)})", t)
    t = t.replace(r"\~", "~").replace(r"\$", "$")
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def split_sections(body: str) -> dict:
    """Cut the callout at its bold section labels."""
    body = re.sub(r"^<callout[^>]*>\s*|\s*</callout>\s*$", "", body.strip())
    labels = {
        "why_now": r"<b>Why now[^<]*</b>",
        "know": r"<b>Know</b>",
        "say": r"<b>Say</b>",
        "watch_out": r"<b>Watch out</b>",
        "contact_clock": r"<b>Contact:</b>",
        "open_before_send": r"<b>Open before send:</b>",
    }
    hits = []
    for key, pat in labels.items():
        m = re.search(pat, body)
        if m:
            hits.append((m.start(), m.end(), key))
    hits.sort()
    out = {}
    head = body[: hits[0][0]] if hits else body
    lines = [l for l in re.split(r"<br\s*/?>|\n", head) if l.strip()]
    out["header"] = plain(lines[0]) if lines else ""
    out["go_call"] = plain("\n".join(lines[1:])) if len(lines) > 1 else ""
    for i, (start, end, key) in enumerate(hits):
        stop = hits[i + 1][0] if i + 1 < len(hits) else len(body)
        out[key] = plain(body[end:stop])
    return out


def checked_on(go_call: str, year: int) -> str | None:
    m = re.search(r"Card checked (\w{3}) (\d{1,2})", go_call)
    if not m or m.group(1) not in MONTHS:
        return None
    return date(year, MONTHS[m.group(1)], int(m.group(2))).isoformat()


def q(v):
    if v is None or v == "":
        return "null"
    return "'" + v[:1200].replace("'", "''") + "'"


def main(path: str, year: int = 2026) -> None:
    with open(path, encoding="utf-8") as f:
        cards = json.load(f)
    print("-- Generated by rep_card_to_sql.py; one upsert per rep card.")
    print("begin;")
    for c in cards:
        s = split_sections(c["callout"])
        pid = c["notion_page_id"].replace("-", "")
        cols = ["header", "go_call", "why_now", "know", "say", "watch_out", "contact_clock", "open_before_send"]
        vals = ", ".join(q(s.get(k)) for k in cols)
        print(f"""
insert into public.rep_cards (client_id, trigger_event_id, contact_id, {", ".join(cols)}, checked_on)
select te.client_id, te.id, te.contact_id, {vals}, {q(checked_on(s.get("go_call", ""), year))}
from public.trigger_events te
where replace(te.notion_page_id, '-', '') = '{pid}'
on conflict (trigger_event_id) do update set
  {", ".join(f"{k} = excluded.{k}" for k in cols)}, checked_on = excluded.checked_on;""")
    print("\ncommit;")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main(sys.argv[1])
